'use client';

import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import type { CodeChange } from '@/types/api';
import { TYPE_LABELS, REAL_DIFF_TYPES } from './type-labels';

/**
 * components/technical-seo/diff-modal.tsx
 *
 * DATA HONESTY: for types in REAL_DIFF_TYPES, newHtml is genuinely
 * applied/appliable markup — shown as a real Before/After code diff,
 * copy-pasteable as-is. For every other type, newHtml today is either
 * empty or a prose sentence wrapped in an HTML comment (e.g.
 * "<!-- SEO Fix: shorten the redirect chain -->") generated by the v2 LLM
 * tier — see type-labels.ts's REAL_DIFF_TYPES comment for exactly why.
 * Showing that as a green "After" code block next to real Before markup
 * would misrepresent it as an applied fix when it's actually just a
 * recommendation in English. This modal renders that case differently —
 * as a labeled recommendation, not as code — rather than papering over
 * the distinction.
 */
export function DiffModal({
  change, onClose, onApply, onDisable, isApplying, isDisabling,
}: {
  change:      CodeChange;
  onClose:     () => void;
  onApply?:    (changeId: string) => void;
  onDisable?:  (changeId: string) => void;
  isApplying?: boolean;
  isDisabling?: boolean;
}) {
  const isRealDiff = REAL_DIFF_TYPES.has(change.type);
  // The v2 LLM tier wraps its suggestion as an HTML comment
  // (<!-- SEO Fix: ... -->) — strip that wrapper for display so the
  // recommendation reads as a sentence, not literal markup.
  const suggestionText = change.newHtml
    ?.replace(/^<!--\s*SEO Fix:\s*/, '')
    .replace(/\s*-->$/, '')
    .trim();

  return (
    <Dialog open onOpenChange={onClose}>
      <DialogContent className="max-w-2xl">
        <DialogHeader>
          <DialogTitle>{TYPE_LABELS[change.type] ?? change.type}</DialogTitle>
        </DialogHeader>
        <p className="text-xs text-muted-foreground truncate mb-4">{change.url}</p>

        {/* Extra info from htmlAttributes */}
        {change.htmlAttributes && Object.keys(change.htmlAttributes).length > 0 && (
          <div className="flex flex-wrap gap-3 mb-4">
            {change.htmlAttributes['wordCount'] && (
              <span className="text-xs text-muted-foreground">
                Word count: <strong>{change.htmlAttributes['wordCount']}</strong>
              </span>
            )}
            {change.htmlAttributes['responseTimeMs'] && (
              <span className="text-xs text-muted-foreground">
                Load time: <strong>{change.htmlAttributes['responseTimeMs']}ms</strong>
              </span>
            )}
            {change.htmlAttributes['pageSizeKb'] && (
              <span className="text-xs text-muted-foreground">
                Page size: <strong>{change.htmlAttributes['pageSizeKb']}KB</strong>
              </span>
            )}
            {change.htmlAttributes['hops'] && (
              <span className="text-xs text-muted-foreground">
                Redirect hops: <strong>{change.htmlAttributes['hops']}</strong>
              </span>
            )}
            {change.htmlAttributes['internalLinkCount'] && (
              <span className="text-xs text-muted-foreground">
                Internal links found: <strong>{change.htmlAttributes['internalLinkCount']}</strong>
              </span>
            )}
          </div>
        )}

        {isRealDiff ? (
          <div className="grid grid-cols-2 gap-4">
            <div>
              <p className="text-xs font-medium text-muted-foreground mb-2 uppercase tracking-wide">Before</p>
              <pre className="text-xs bg-muted/50 border border-border rounded p-3 overflow-auto max-h-48 whitespace-pre-wrap break-all">
                {change.oldHtml || '(empty)'}
              </pre>
            </div>
            <div>
              <p className="text-xs font-medium text-green-500 mb-2 uppercase tracking-wide">After — copy this in</p>
              <pre className="text-xs bg-green-500/5 border border-green-500/20 rounded p-3 overflow-auto max-h-48 whitespace-pre-wrap break-all">
                {change.newHtml || '(pending generation)'}
              </pre>
            </div>
          </div>
        ) : (
          <div>
            <p className="text-xs font-medium text-muted-foreground mb-2 uppercase tracking-wide">
              What was found
            </p>
            <pre className="text-xs bg-muted/50 border border-border rounded p-3 overflow-auto max-h-48 whitespace-pre-wrap break-all mb-4">
              {change.oldHtml || '(empty)'}
            </pre>

            <p className="text-xs font-medium text-amber-500 mb-2 uppercase tracking-wide">
              Recommendation (not applied automatically)
            </p>
            <p className="text-sm bg-amber-500/5 border border-amber-500/20 rounded p-3">
              {suggestionText || 'No specific recommendation generated yet for this fix.'}
            </p>
          </div>
        )}

        {(onApply || onDisable) && change.status === 'pending' && (
          <div className="flex gap-2 mt-4">
            {onApply && (
              <Button size="sm" onClick={() => onApply(change._id)} disabled={isApplying || isDisabling}>
                Apply
              </Button>
            )}
            {onDisable && (
              <Button size="sm" variant="outline" onClick={() => onDisable(change._id)} disabled={isApplying || isDisabling}>
                Disable
              </Button>
            )}
          </div>
        )}
      </DialogContent>
    </Dialog>
  );
}
